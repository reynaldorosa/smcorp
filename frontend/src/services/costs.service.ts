export interface PaginatedResponse<T> {
  data: T[];
  meta: {
    total: number;
    page: number;
    limit: number;
    totalPages: number;
  };
}

export interface CostFilters {
  category?: CostCategory;
  isAuditable?: boolean;
  startDate?: Date;
  endDate?: Date;
  page?: number;
  limit?: number;
}

export const costsService = {
  /**
   * Busca todos os custos (paginado)
   */
  getAll: async (filters?: CostFilters): Promise<PaginatedResponse<Cost>> => {
    const params: Record<string, string | number | boolean> = {
      page: filters?.page || 1,
      limit: filters?.limit || 20,
    };

    if (filters?.category) params.category = filters.category;
    if (filters?.isAuditable !== undefined) params.isAuditable = filters.isAuditable;
    if (filters?.startDate) params.startDate = filters.startDate.toISOString();
    if (filters?.endDate) params.endDate = filters.endDate.toISOString();

    const response = await api.get('/costs', { params });
    return response.data;
  },

  /**
   * Busca um custo por ID
   */
  getById: async (id: string): Promise<Cost> => {
    const response = await api.get(`/costs/${id}`);
    return response.data;
  },

  /**
   * Cria um novo custo
   */
  create: async (data: CreateCostDTO): Promise<Cost> => {
    const response = await api.post('/costs', data);
    return response.data;
  },

  /**
   * Atualiza um custo existente
   */
  update: async (id: string, data: UpdateCostDTO): Promise<Cost> => {
    const response = await api.put(`/costs/${id}`, data);
    return response.data;
  },

  /**
   * Remove um custo (soft delete)
   */
  delete: async (id: string): Promise<void> => {
    await api.delete(`/costs/${id}`);
  },

  /**
   * Busca custos auditáveis (para vincular a cursos)
   */
  getAuditable: async (): Promise<Cost[]> => {
    const response = await api.get('/costs', { 
      params: { isAuditable: true, limit: 100 } 
    });
    return response.data.data || response.data;
  },

  /**
   * Busca custos por categoria
   */
  getByCategory: async (category: CostCategory): Promise<Cost[]> => {
    const response = await api.get('/costs', { 
      params: { category, limit: 100 } 
    });
    return response.data.data || response.data;
  },

  getCriteria: async (): Promise<CostCriterion[]> => {
    const response = await api.get('/costs/criteria', {
      params: { page: 1, limit: 200 },
    });
    const data = response.data?.data || [];
    return data.map((item: ApiCostCriterion) => mapCriterionFromApi(item));
  },

  createCriterion: async (data: CreateCostCriterionDTO): Promise<CostCriterion> => {
    const response = await api.post('/costs/criteria', {
      name: data.name,
      frequency: mapFrequencyToApi(data.frequency),
      linkage: mapLinkageToApi(data.linkage),
      dueCriterion: mapDueCriterionToApi(data.dueCriterion),
      daysUntilDue: data.daysUntilDue,
      monthlyClosingDay: data.monthlyClosingDay,
      daysAfterClosing: data.daysAfterClosing,
      notes: serializeCriterionNotes(data.notes, data.triggers),
    });
    return mapCriterionFromApi(response.data);
  },

  updateCriterion: async (id: string, data: UpdateCostCriterionDTO): Promise<CostCriterion> => {
    const response = await api.put(`/costs/criteria/${id}`, {
      ...(data.name !== undefined && { name: data.name }),
      ...(data.frequency !== undefined && { frequency: mapFrequencyToApi(data.frequency) }),
      ...(data.linkage !== undefined && { linkage: mapLinkageToApi(data.linkage) }),
      ...(data.dueCriterion !== undefined && { dueCriterion: mapDueCriterionToApi(data.dueCriterion) }),
      ...(data.daysUntilDue !== undefined && { daysUntilDue: data.daysUntilDue }),
      ...(data.monthlyClosingDay !== undefined && { monthlyClosingDay: data.monthlyClosingDay }),
      ...(data.daysAfterClosing !== undefined && { daysAfterClosing: data.daysAfterClosing }),
      ...(data.active !== undefined && { isActive: data.active }),
      notes: serializeCriterionNotes(data.notes, data.triggers),
    });
    return mapCriterionFromApi(response.data);
  },

  deleteCriterion: async (id: string): Promise<void> => {
    await api.delete(`/costs/criteria/${id}`);
  },

  getEntries: async (page = 1, limit = 500): Promise<PaginatedResponse<CostEntry>> => {
    const response = await api.get('/costs/entries', { params: { page, limit } });
    const payload = response.data;
    return {
      data: (payload.data || []).map((item: ApiCostEntry) => mapCostEntryFromApi(item)),
      meta: payload.meta,
    };
  },

  createEntry: async (data: CreateCostEntryDTO): Promise<CostEntry> => {
    const response = await api.post('/costs/entries', {
      ...data,
      status: mapCostEntryStatusToApi(data.status || 'Pending'),
    });
    return mapCostEntryFromApi(response.data);
  },

  updateEntry: async (id: string, data: UpdateCostEntryDTO): Promise<CostEntry> => {
    const response = await api.put(`/costs/entries/${id}`, {
      ...data,
      ...(data.status !== undefined && { status: mapCostEntryStatusToApi(data.status) }),
    });
    return mapCostEntryFromApi(response.data);
  },

  payEntry: async (id: string, paidAt?: string): Promise<CostEntry> => {
    const response = await api.post(`/costs/entries/${id}/pay`, { paidAt });
    return mapCostEntryFromApi(response.data);
  },

  deleteEntry: async (id: string): Promise<void> => {
    await api.delete(`/costs/entries/${id}`);
  },

  /**
   * Busca resumo de custos por período
   */
  getSummaryByPeriod: async (startDate: Date, endDate: Date): Promise<{
    total: number;
    byCategory: Record<CostCategory, number>;
    recurring: number;
    oneTime: number;
  }> => {
    const response = await api.get('/costs', {
      params: {
        startDate: startDate.toISOString(),
        endDate: endDate.toISOString(),
        limit: 1000,
      },
    });

    const costs: Cost[] = response.data.data || response.data;
    
    const summary = {
      total: 0,
      byCategory: {} as Record<CostCategory, number>,
      recurring: 0,
      oneTime: 0,
    };

    costs.forEach((cost) => {
      const amount = Number(cost.amount);
      summary.total += amount;
      
      if (!summary.byCategory[cost.category]) {
        summary.byCategory[cost.category] = 0;
      }
      summary.byCategory[cost.category] += amount;
      
      if (cost.isRecurring) {
        summary.recurring += amount;
      } else {
        summary.oneTime += amount;
      }
    });

    return summary;
  },
};
