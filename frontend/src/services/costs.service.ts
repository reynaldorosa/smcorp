type ApiCostCriterion = {
  id: string;
  code: string;
  name: string;
  frequency: 'MONTHLY' | 'DAILY' | 'ONE_TIME';
  linkage: 'ENROLLED_STUDENT' | 'NOT_LINKED' | 'INSTRUCTOR';
  dueCriterion:
    | 'COURSE_END_DATE'
    | 'THIRTY_DAYS_AFTER_END'
    | 'MONTHLY_CLOSING'
    | 'SPECIFIC_DATE'
    | 'NO_DUE';
  daysUntilDue?: number;
  monthlyClosingDay?: number;
  daysAfterClosing?: number;
  isActive: boolean;
  notes?: string;
  createdAt: string;
  updatedAt: string;
};

const TRIGGERS_PREFIX = '__TRIGGERS__=';

function mapFrequencyFromApi(value: ApiCostCriterion['frequency']): CostCriterion['frequency'] {
  if (value === 'MONTHLY') return 'Monthly';
  if (value === 'DAILY') return 'Daily';
  return 'OneTime';
}

function mapFrequencyToApi(value: CostCriterion['frequency']): ApiCostCriterion['frequency'] {
  if (value === 'Monthly') return 'MONTHLY';
  if (value === 'Daily') return 'DAILY';
  return 'ONE_TIME';
}

function mapLinkageFromApi(value: ApiCostCriterion['linkage']): CostCriterion['linkage'] {
  if (value === 'ENROLLED_STUDENT') return 'EnrolledStudent';
  if (value === 'INSTRUCTOR') return 'Instructor';
  return 'NotLinked';
}

function mapLinkageToApi(value: CostCriterion['linkage']): ApiCostCriterion['linkage'] {
  if (value === 'EnrolledStudent') return 'ENROLLED_STUDENT';
  if (value === 'Instructor') return 'INSTRUCTOR';
  return 'NOT_LINKED';
}

function mapDueCriterionFromApi(value: ApiCostCriterion['dueCriterion']): CostCriterion['dueCriterion'] {
  if (value === 'COURSE_END_DATE') return 'CourseEndDate';
  if (value === 'THIRTY_DAYS_AFTER_END') return '30DaysAfterEnd';
  if (value === 'MONTHLY_CLOSING') return 'MonthlyClosing';
  if (value === 'SPECIFIC_DATE') return 'SpecificDate';
  return 'NoDue';
}

function mapDueCriterionToApi(value: CostCriterion['dueCriterion']): ApiCostCriterion['dueCriterion'] {
  if (value === 'CourseEndDate') return 'COURSE_END_DATE';
  if (value === '30DaysAfterEnd') return 'THIRTY_DAYS_AFTER_END';
  if (value === 'MonthlyClosing') return 'MONTHLY_CLOSING';
  if (value === 'SpecificDate') return 'SPECIFIC_DATE';
  return 'NO_DUE';
}

function parseCriterionNotes(notes?: string): { notes?: string; triggers?: string[] } {
  if (!notes) return {};
  const line = notes
    .split('\n')
    .map((item) => item.trim())
    .find((item) => item.startsWith(TRIGGERS_PREFIX));

  if (!line) return { notes };

  try {
    const parsed = JSON.parse(line.slice(TRIGGERS_PREFIX.length)) as {
      triggers?: string[];
      notes?: string;
    };

    const plain = notes
      .split('\n')
      .filter((item) => !item.trim().startsWith(TRIGGERS_PREFIX))
      .join('\n')
      .trim();

    return {
      triggers: Array.isArray(parsed.triggers) ? parsed.triggers : [],
      notes: parsed.notes || plain || undefined,
    };
  } catch {
    return { notes };
  }
}

function serializeCriterionNotes(notes?: string, triggers?: string[]): string | undefined {
  const payload = JSON.stringify({
    notes: notes?.trim() || undefined,
    triggers: triggers && triggers.length > 0 ? triggers : [],
  });

  const serialized = `${TRIGGERS_PREFIX}${payload}`;
  return serialized;
}

function mapCriterionFromApi(item: ApiCostCriterion): CostCriterion {
  const parsed = parseCriterionNotes(item.notes);

  return {
    id: item.id,
    code: item.code,
    name: item.name,
    frequency: mapFrequencyFromApi(item.frequency),
    linkage: mapLinkageFromApi(item.linkage),
    dueCriterion: mapDueCriterionFromApi(item.dueCriterion),
    daysUntilDue: item.daysUntilDue ?? undefined,
    monthlyClosingDay: item.monthlyClosingDay ?? undefined,
    daysAfterClosing: item.daysAfterClosing ?? undefined,
    active: item.isActive,
    triggers: parsed.triggers,
    notes: parsed.notes,
    createdAt: item.createdAt,
    updatedAt: item.updatedAt,
  };
}

function mapCostEntryStatusFromApi(status: ApiCostEntry['status']): CostEntry['status'] {
  if (status === 'PAID') return 'Paid';
  if (status === 'OVERDUE') return 'Overdue';
  if (status === 'CANCELLED') return 'Cancelled';
  return 'Pending';
}

function mapCostEntryStatusToApi(
  status: NonNullable<CreateCostEntryDTO['status']>
): ApiCostEntry['status'] {
  if (status === 'Paid') return 'PAID';
  if (status === 'Overdue') return 'OVERDUE';
  if (status === 'Cancelled') return 'CANCELLED';
  return 'PENDING';
}

function mapCostEntryFromApi(item: ApiCostEntry): CostEntry {
  return {
    id: item.id,
    code: item.code,
    auditableCostId: item.auditableCostId,
    costCriterionId: item.costCriterionId || undefined,
    studentId: item.studentId || undefined,
    classId: item.classId || undefined,
    supplierId: item.supplierId || undefined,
    instructorId: item.instructorId || undefined,
    companyId: item.companyId || undefined,
    examNumber: item.examNumber || undefined,
    examName: item.examName || undefined,
    value: Number(item.value),
    generatedAt: item.generatedAt,
    dueDate: item.dueDate,
    paidAt: item.paidAt || undefined,
    status: mapCostEntryStatusFromApi(item.status),
    notes: item.notes || undefined,
    autoGenerated: item.autoGenerated,
    triggerAction: item.triggerAction || undefined,
    createdAt: item.createdAt,
    updatedAt: item.updatedAt,
  };
}

